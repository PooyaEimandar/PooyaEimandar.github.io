import { mkdir, readFile, writeFile } from "node:fs/promises";

const projectRoot = new URL("../", import.meta.url);
const timelineDataUrl = new URL("data/timeline.json", projectRoot);
const timelineDirectoryUrl = new URL("timeline/", projectRoot);
const timelinePageUrl = new URL("timeline/index.html", projectRoot);

function escapeHtml(value) {
  return String(value)
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;")
    .replaceAll("'", "&#39;");
}

function assertSafeId(value, label) {
  if (typeof value !== "string" || !/^[a-z0-9-]+$/.test(value)) {
    throw new Error(`${label} must contain only lowercase letters, numbers, and hyphens.`);
  }
  return value;
}

function renderLinks(links) {
  if (!Array.isArray(links) || links.length === 0) {
    return "";
  }

  const items = links.map((link) => {
    const url = new URL(link.url);
    if (url.protocol !== "https:" && url.protocol !== "http:") {
      throw new Error(`Timeline link uses an unsupported protocol: ${link.url}`);
    }

    return `                  <li><a href="${escapeHtml(url.href)}" target="_blank" rel="noopener noreferrer">${escapeHtml(link.label)}</a></li>`;
  }).join("\n");

  return `
                <ul class="timeline-entry-links" aria-label="Related links">
${items}
                </ul>`;
}

function renderEntry(entry) {
  const id = assertSafeId(entry.id, "Timeline entry id");
  const year = String(entry.year);
  if (!/^\d{4}$/.test(year)) {
    throw new Error(`Timeline entry ${id} has an invalid year.`);
  }

  return `          <li id="${id}">
            <time datetime="${year}">${year}</time>
            <div>
              <h3>${escapeHtml(entry.title)}</h3>
              <p>${escapeHtml(entry.text)}</p>${renderLinks(entry.links)}
            </div>
          </li>`;
}

function renderSection(section) {
  const id = assertSafeId(section.id, "Timeline section id");
  if (!Array.isArray(section.entries) || section.entries.length === 0) {
    throw new Error(`Timeline section ${id} must contain at least one entry.`);
  }

  return `      <section class="timeline-group" aria-labelledby="${id}-title">
        <header>
          <p>${escapeHtml(section.range)}</p>
          <h2 id="${id}-title">${escapeHtml(section.title)}</h2>
        </header>
        <ol>
${section.entries.map(renderEntry).join("\n")}
        </ol>
      </section>`;
}

const data = JSON.parse(await readFile(timelineDataUrl, "utf8"));
if (!Array.isArray(data.sections) || data.sections.length === 0) {
  throw new Error("Timeline data must contain at least one section.");
}

const milestoneCount = data.sections.reduce((count, section) => count + section.entries.length, 0);
const currentYear = new Date().getUTCFullYear();
const sections = data.sections.map(renderSection).join("\n\n");

